// copies MapLibre's worker and shared bundle from node_modules into public/maplibre/<version>/ on every install.
// The maps run the worker from a self-hosted file (Turbopack drops MapLibre's inline worker) and the worker must be the exact
// version of the library that posts it messages. A hand-copied file went stale after a Dependabot upgrade and every vector map
// style silently failed to parse tiles while the raster satellite view kept working. Copying on install makes that impossible,
// and the version in the folder name means a browser or CDN can never serve an older worker for a newer library.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const lib = join(process.cwd(), "node_modules", "maplibre-gl")
if (!existsSync(lib)) process.exit(0)
const { version } = JSON.parse(readFileSync(join(lib, "package.json"), "utf8"))
const out = join(process.cwd(), "public", "maplibre")
const dest = join(out, version)
mkdirSync(dest, { recursive: true })
for (const f of ["maplibre-gl-worker.mjs", "maplibre-gl-shared.mjs"]) cpSync(join(lib, "dist", f), join(dest, f))
// keep only the current version
for (const d of readdirSync(out)) if (d !== version) rmSync(join(out, d), { recursive: true, force: true })
// the components read the version from this generated file to build the worker path
writeFileSync(join(process.cwd(), "lib", "maplibre-version.ts"), `// generated by scripts/sync-maplibre-worker.mjs on install, do not edit\nexport const MAPLIBRE_VERSION = "${version}"\n`)
console.log(`maplibre worker ${version} copied to public/maplibre/${version}`)
